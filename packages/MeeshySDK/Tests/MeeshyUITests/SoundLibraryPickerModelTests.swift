import XCTest
@testable import MeeshySDK
@testable import MeeshyUI

/// Faux service : aucun réseau, et il ENREGISTRE ce qu'on lui demande — c'est
/// ce qui permet de prouver que la recherche part bien au serveur sur l'onglet
/// Tendances et pas sur « Mes sons ».
final class FakeSoundLibraryService: SoundLibraryServiceProviding, @unchecked Sendable {
    var mineResult: SoundPage = SoundPage(sounds: [], nextCursor: nil)
    var trendingResult: [APISound] = []
    var renameResult: APISound?

    private(set) var mineCalls: [(query: String?, cursor: Date?)] = []
    private(set) var trendingCalls: [String?] = []
    private(set) var renameCalls: [(String, String)] = []

    func mySounds(query: String?, cursor: Date?, limit: Int) async throws -> SoundPage {
        mineCalls.append((query, cursor))
        return mineResult
    }

    func trendingSounds(query: String?, limit: Int) async throws -> [APISound] {
        trendingCalls.append(query)
        return trendingResult
    }

    func rename(soundId: String, title: String) async throws -> APISound {
        renameCalls.append((soundId, title))
        guard let renameResult else { throw URLError(.badServerResponse) }
        return renameResult
    }
}

func makeSound(id: String = "s1", title: String = "", usageCount: Int = 0,
               createdAt: Date? = nil, uploader: APISoundUploader? = nil,
               coverUrl: String? = nil, coverThumbHash: String? = nil) -> APISound {
    APISound(id: id, title: title, fileUrl: "/api/v1/static/\(id).m4a",
             durationMs: 4000, waveform: [], usageCount: usageCount,
             isPublic: true, isAutoGenerated: title.isEmpty,
             coverUrl: coverUrl, coverThumbHash: coverThumbHash,
             createdAt: createdAt, uploader: uploader)
}

@MainActor
final class SoundLibraryPickerModelTests: XCTestCase {

    // MARK: - Libellé

    /// Le discriminant est la PRÉSENCE d'un titre, pas `isAutoGenerated` : un son
    /// capturé puis nommé doit montrer son titre.
    func test_displayTitle_authoredTitle_wins() {
        let sound = makeSound(title: "Ma prod")
        XCTAssertEqual(SoundLibraryPickerModel.displayTitle(for: sound), "Ma prod")
    }

    func test_displayTitle_untitled_fallsBackToTheUploadDate() {
        let date = Date(timeIntervalSince1970: 1_785_000_000)
        let shown = SoundLibraryPickerModel.displayTitle(for: makeSound(title: "", createdAt: date))
        // Pas de libellé « Son original » venu du serveur : ce serait du français
        // gravé, servi tel quel dans les sept langues.
        XCTAssertFalse(shown.isEmpty)
        XCTAssertNotEqual(shown, "")
    }

    func test_displayTitle_whitespaceOnlyTitle_countsAsUntitled() {
        let date = Date(timeIntervalSince1970: 1_785_000_000)
        let blank = SoundLibraryPickerModel.displayTitle(for: makeSound(title: "   ", createdAt: date))
        let none = SoundLibraryPickerModel.displayTitle(for: makeSound(title: "", createdAt: date))
        XCTAssertEqual(blank, none)
    }

    // MARK: - Crédit

    func test_authorLabel_prefersDisplayNameThenHandle() {
        let named = makeSound(uploader: APISoundUploader(id: "u", username: "alice", displayName: "Alice"))
        XCTAssertEqual(named.authorLabel, "Alice")

        let handleOnly = makeSound(uploader: APISoundUploader(id: "u", username: "alice", displayName: nil))
        XCTAssertEqual(handleOnly.authorLabel, "@alice")

        XCTAssertNil(makeSound(uploader: nil).authorLabel)
    }

    // MARK: - Onglets

    func test_reload_mineTab_callsTheMineRoute() async {
        let service = FakeSoundLibraryService()
        service.mineResult = SoundPage(sounds: [makeSound()], nextCursor: nil)
        let model = SoundLibraryPickerModel(service: service)

        await model.reload()

        XCTAssertEqual(service.mineCalls.count, 1)
        XCTAssertTrue(service.trendingCalls.isEmpty)
        XCTAssertEqual(model.sounds.count, 1)
    }

    func test_reload_trendingTab_sendsTheQueryToTheServer() async {
        let service = FakeSoundLibraryService()
        let model = SoundLibraryPickerModel(service: service)
        model.tab = .trending
        model.query = "alice"

        await model.reload()

        // La recherche publique part au SERVEUR : elle porte sur le titre ou le
        // pseudo, ce qu'un filtre local ne saurait pas faire sur une page.
        XCTAssertEqual(service.trendingCalls.last, "alice")
    }

    func test_reload_failure_leavesAnEmptyListRatherThanCrashing() async {
        final class Failing: SoundLibraryServiceProviding, @unchecked Sendable {
            func mySounds(query: String?, cursor: Date?, limit: Int) async throws -> SoundPage {
                throw URLError(.notConnectedToInternet)
            }
            func trendingSounds(query: String?, limit: Int) async throws -> [APISound] { [] }
            func rename(soundId: String, title: String) async throws -> APISound {
                throw URLError(.badURL)
            }
        }
        let model = SoundLibraryPickerModel(service: Failing())
        await model.reload()
        XCTAssertTrue(model.sounds.isEmpty)
    }

    // MARK: - Pagination

    func test_loadMore_appendsRatherThanReplacing() async {
        let service = FakeSoundLibraryService()
        let cursor = Date(timeIntervalSince1970: 1_785_000_000)
        service.mineResult = SoundPage(sounds: [makeSound(id: "s1")], nextCursor: cursor)
        let model = SoundLibraryPickerModel(service: service)
        await model.reload()

        service.mineResult = SoundPage(sounds: [makeSound(id: "s2")], nextCursor: nil)
        await model.loadMore()

        XCTAssertEqual(model.sounds.map(\.id), ["s1", "s2"])
        XCTAssertEqual(service.mineCalls.last?.cursor, cursor)
    }

    func test_loadMore_withoutCursor_doesNothing() async {
        let service = FakeSoundLibraryService()
        service.mineResult = SoundPage(sounds: [makeSound()], nextCursor: nil)
        let model = SoundLibraryPickerModel(service: service)
        await model.reload()

        await model.loadMore()

        XCTAssertEqual(service.mineCalls.count, 1)
    }

    /// L'onglet Tendances n'est pas paginé côté serveur : proposer « charger
    /// plus » y afficherait une roue qui ne finit jamais.
    func test_canLoadMore_isFalseOnTheTrendingTab() async {
        let service = FakeSoundLibraryService()
        let model = SoundLibraryPickerModel(service: service)
        model.tab = .trending
        await model.reload()
        XCTAssertFalse(model.canLoadMore)
    }

    // MARK: - Renommage

    func test_commitRename_replacesTheRowInPlace() async {
        let service = FakeSoundLibraryService()
        service.mineResult = SoundPage(sounds: [makeSound(id: "s1"), makeSound(id: "s2")], nextCursor: nil)
        service.renameResult = makeSound(id: "s1", title: "Ma prod")
        let model = SoundLibraryPickerModel(service: service)
        await model.reload()

        await model.commitRename(makeSound(id: "s1"), title: "Ma prod")

        XCTAssertEqual(service.renameCalls.first?.1, "Ma prod")
        // EN PLACE : recharger la liste ferait sauter le défilement au moment
        // précis où l'utilisateur regarde ce qu'il vient de nommer.
        XCTAssertEqual(model.sounds.map(\.id), ["s1", "s2"])
        XCTAssertEqual(model.sounds.first?.title, "Ma prod")
        XCTAssertNil(model.renaming)
    }

    func test_commitRename_emptyTitle_isSentAsIs() async {
        // Vider un titre est le seul recours de l'auteur contre un titre
        // malheureux, sans qu'un administrateur coupe le son entier.
        let service = FakeSoundLibraryService()
        service.renameResult = makeSound(id: "s1", title: "")
        let model = SoundLibraryPickerModel(service: service)

        await model.commitRename(makeSound(id: "s1"), title: "")

        XCTAssertEqual(service.renameCalls.first?.1, "")
    }

    func test_commitRename_failure_keepsThePreviousTitle() async {
        let service = FakeSoundLibraryService()
        service.mineResult = SoundPage(sounds: [makeSound(id: "s1", title: "Avant")], nextCursor: nil)
        service.renameResult = nil // provoque une erreur
        let model = SoundLibraryPickerModel(service: service)
        await model.reload()

        await model.commitRename(makeSound(id: "s1"), title: "Après")

        XCTAssertEqual(model.sounds.first?.title, "Avant")
        XCTAssertNil(model.renaming)
    }

    // MARK: - Prévisualisation

    func test_togglePreview_isExclusiveAndReversible() {
        let model = SoundLibraryPickerModel(service: FakeSoundLibraryService())
        let a = makeSound(id: "a"), b = makeSound(id: "b")

        model.togglePreview(a)
        XCTAssertEqual(model.previewingId, "a")
        model.togglePreview(b)
        XCTAssertEqual(model.previewingId, "b", "un seul son s'écoute à la fois")
        model.togglePreview(b)
        XCTAssertNil(model.previewingId)
    }

    // MARK: - Filtre local

    func test_localFilter_matchesTitleUsernameAndDisplayName() {
        let sounds = [
            makeSound(id: "1", title: "Ambiance café"),
            makeSound(id: "2", uploader: APISoundUploader(id: "u", username: "alice")),
            makeSound(id: "3", uploader: APISoundUploader(id: "u", username: "bob", displayName: "Robert")),
        ]
        XCTAssertEqual(SoundLibraryService.filterLocally(sounds, query: "café").map(\.id), ["1"])
        XCTAssertEqual(SoundLibraryService.filterLocally(sounds, query: "alice").map(\.id), ["2"])
        XCTAssertEqual(SoundLibraryService.filterLocally(sounds, query: "robert").map(\.id), ["3"])
    }

    func test_localFilter_ignoresCaseAndDiacritics() {
        // « cafe » doit trouver « café » : sinon la recherche punit l'utilisateur
        // qui tape vite.
        let sounds = [makeSound(id: "1", title: "Ambiance Café")]
        XCTAssertEqual(SoundLibraryService.filterLocally(sounds, query: "cafe").map(\.id), ["1"])
        XCTAssertEqual(SoundLibraryService.filterLocally(sounds, query: "AMBIANCE").map(\.id), ["1"])
    }

    func test_localFilter_emptyQuery_returnsEverything() {
        let sounds = [makeSound(id: "1"), makeSound(id: "2")]
        XCTAssertEqual(SoundLibraryService.filterLocally(sounds, query: nil).count, 2)
        XCTAssertEqual(SoundLibraryService.filterLocally(sounds, query: "   ").count, 2)
    }
}
