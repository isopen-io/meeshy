/// Faux service : aucun réseau, et il ENREGISTRE ce qu'on lui demande — c'est
/// ce qui permet de prouver que la recherche part bien au serveur sur l'onglet
/// Tendances et pas sur « Mes sons ».
final class FakeSoundLibraryService: SoundLibraryServiceProviding, @unchecked Sendable {
    var mineResult: SoundPage = SoundPage(sounds: [], nextCursor: nil)
    var trendingResult: [APISound] = []
    var renameResult: APISound?

    private(set) var mineCalls: [(query: String?, cursor: Date?)] = []
    private(set) var trendingCalls: [String?] = []
    private(set) var renameCalls: [(String, String)] = []

    func mySounds(query: String?, cursor: Date?, limit: Int) async throws -> SoundPage {
        mineCalls.append((query, cursor))
        return mineResult
    }

    func trendingSounds(query: String?, limit: Int) async throws -> [APISound] {
        trendingCalls.append(query)
        return trendingResult
    }

    func rename(soundId: String, title: String) async throws -> APISound {
        renameCalls.append((soundId, title))
        guard let renameResult else { throw URLError(.badServerResponse) }
        return renameResult
    }

    /// La page du son a son propre modèle et ses propres tests
    /// (`SoundDetailModelTests`) : ici on satisfait le protocole sans plus.
    func posts(soundId: String, cursor: Date?, limit: Int) async throws -> SoundPostPage {
        SoundPostPage(posts: [], nextCursor: nil)
    }
}

func makeSound(id: String = "s1", title: String = "", usageCount: Int = 0,
               postCount: Int = 0, playCount: Int = 0,
               createdAt: Date? = nil, uploader: APISoundUploader? = nil,
               coverUrl: String? = nil, coverThumbHash: String? = nil) -> APISound {
    APISound(id: id, title: title, fileUrl: "/api/v1/static/\(id).m4a",
             durationMs: 4000, waveform: [], usageCount: usageCount,
             postCount: postCount, playCount: playCount,
             isPublic: true, isAutoGenerated: title.isEmpty,
             coverUrl: coverUrl, coverThumbHash: coverThumbHash,
             createdAt: createdAt, uploader: uploader)
}

/// Faux lecteur : aucun audio, aucun réseau, et il ENREGISTRE les appels — c'est
/// ce qui permet de prouver qu'un son déjà en cache ne passe pas par l'état de
/// préparation, et qu'un aperçu abandonné coupe bien le précédent.
@MainActor
final class FakeSoundPreview: SoundPreviewing {
    /// Faux par défaut : le cas coûteux (téléchargement) est celui qui a des
    /// états intermédiaires, donc celui qu'il faut couvrir sans y penser.
    var readyInstantly = false
    /// Quand vrai, `play` reste suspendu jusqu'à `release()` — c'est ce qui
    /// rend l'état « préparation » observable.
    var blocksUntilReleased = false
    /// Simule un échec de lecture : réseau coupé, fichier tronqué, format que
    /// `AVAudioPlayer` refuse.
    var playSucceeds = true

    private var gate: CheckedContinuation<Void, Never>?
    private(set) var playedIds: [String] = []
    private(set) var stopCount = 0

    private let finishedSubject = PassthroughSubject<Void, Never>()
    var finished: AnyPublisher<Void, Never> { finishedSubject.eraseToAnyPublisher() }

    func isReadyToPlayInstantly(_ sound: APISound) -> Bool { readyInstantly }

    /// Rejoue le « terminé » parasite qu'émettait le vrai lecteur au démarrage
    /// (`playLocalFile` commence par un `stop()` interne).
    var emitsSpuriousFinishOnPlay = false

    /// Ids dont l'appel `play` a effectivement RENDU. `playedIds` dit
    /// seulement qu'il a été APPELÉ — un test qui attend l'après-lecture ne
    /// peut pas s'y fier, et un test d'annulation qui n'attend rien passe au
    /// vert parce que la tâche n'a pas encore tourné, pas parce qu'elle a été
    /// annulée.
    private(set) var completedPlayIds: [String] = []

    @discardableResult
    func play(_ sound: APISound) async -> Bool {
        playedIds.append(sound.id)
        if emitsSpuriousFinishOnPlay { finishedSubject.send() }
        guard blocksUntilReleased else {
            completedPlayIds.append(sound.id)
            return playSucceeds
        }
        await withCheckedContinuation { gate = $0 }
        completedPlayIds.append(sound.id)
        return playSucceeds
    }

    func release() { gate?.resume(); gate = nil }
    func stop() { stopCount += 1 }
    func simulateNaturalEnd() { finishedSubject.send() }
}

