    func test_togglePreview_surLeSonEnCours_lArrete() async {
        let preview = FakeSoundPreview()
        preview.readyInstantly = true
        let model = makeModel(preview)
        let a = makeSound(id: "a")

        model.togglePreview(a)
        model.togglePreview(a)

        XCTAssertNil(model.previewingId)
        XCTAssertEqual(preview.stopCount, 1, "l'audio doit vraiment être coupé, pas seulement l'état")
    }

    func test_togglePreview_pendantLaPreparation_annuleSansJouer() async {
        // Marteler play/stop ne doit rien lancer : le téléchargement, lui,
        // continue et finit en cache (cf. SoundPreviewPlayer).
        let preview = FakeSoundPreview()
        preview.blocksUntilReleased = true
        let model = makeModel(preview)
        let a = makeSound(id: "a")

        model.togglePreview(a)
        await Task.yield()
        model.togglePreview(a)
        preview.release()
        // Attendre que `play` ait RENDU : sans cette preuve, deux `nil`
        // attesteraient seulement que la tâche n'a pas encore tourné, ce que
        // l'annulation est précisément censée rendre indiscernable.
        await waitUntil("l'appel play rend la main") { preview.completedPlayIds.contains("a") }
        await Task.yield()

        XCTAssertNil(model.previewingId)
        XCTAssertNil(model.preparingId)
    }

    func test_terminéParasiteAuDemarrage_neLaissePasLaLigneEteinte() async {
        // Le vrai lecteur dédoublonne désormais `$isPlaying` pour ne plus
        // l'émettre ; ce test garde l'autre bout, côté modèle, pour que la
        // correction ne repose pas sur un seul point.
        let preview = FakeSoundPreview()
        preview.readyInstantly = true
        preview.emitsSpuriousFinishOnPlay = true
        let model = makeModel(preview)

        model.togglePreview(makeSound(id: "a"))
        await Task.yield()
        await Task.yield()

        XCTAssertEqual(model.previewingId, "a")
    }

    func test_echecDeLecture_neLaissePasLaLigneSurStop() async {
        // Réseau coupé ou fichier illisible : afficher « stop » pour un son
        // muet enfermerait l'utilisateur — il n'y a rien à arrêter.
        let preview = FakeSoundPreview()
        preview.readyInstantly = true
        preview.playSucceeds = false
        let model = makeModel(preview)

        model.togglePreview(makeSound(id: "a"))
        await Task.yield()
        await Task.yield()

        XCTAssertNil(model.previewingId)
        XCTAssertNil(model.preparingId)
    }

    func test_finNaturelle_remetLaLigneEnLecturePossible() async {
        let preview = FakeSoundPreview()
        preview.readyInstantly = true
        let model = makeModel(preview)
        model.togglePreview(makeSound(id: "a"))

        preview.simulateNaturalEnd()

        XCTAssertNil(model.previewingId, "sinon la ligne reste bloquée sur « stop » pour toujours")
    }

    func test_stopPreview_coupeLAudioEtLesDeuxEtats() async {
        let preview = FakeSoundPreview()
        preview.readyInstantly = true
        let model = makeModel(preview)
        model.togglePreview(makeSound(id: "a"))

        model.stopPreview()

        XCTAssertNil(model.previewingId)
        XCTAssertNil(model.preparingId)
        XCTAssertGreaterThanOrEqual(preview.stopCount, 1)
    }

