import Foundation
import SwiftUI
import Combine
import MeeshySDK

/// État du sélecteur de sons. Séparé de la vue pour être testable sans SwiftUI.
@MainActor
public final class SoundLibraryPickerModel: ObservableObject {
    @Published public var tab: SoundLibraryPicker.Tab = .mine
    @Published public var query: String = ""
    @Published public private(set) var sounds: [APISound] = []
    @Published public private(set) var isLoading = false
    @Published public private(set) var previewingId: String?
    @Published public var renaming: APISound?

    private let service: SoundLibraryServiceProviding
    private var nextCursor: Date?
    private var loadedOnce = false
    private var cancellables = Set<AnyCancellable>()

    public init(service: SoundLibraryServiceProviding) {
        self.service = service
        bind()
    }

    /// Recherche et bascule d'onglet pilotées ICI, par Combine, plutôt que par
    /// des `.onChange` dans la vue : la règle du dépôt les proscrit, et le
    /// débounce devient testable sans SwiftUI.
    ///
    /// Le débounce n'est pas cosmétique — sans lui, chaque frappe partait au
    /// serveur sur l'onglet Tendances, dont la clause `contains` est un
    /// balayage de collection.
    private func bind() {
        $query
            .dropFirst()
            .debounce(for: .milliseconds(300), scheduler: DispatchQueue.main)
            .removeDuplicates()
            .sink { [weak self] _ in Task { @MainActor in await self?.reload() } }
            .store(in: &cancellables)

        // Pas de débounce sur l'onglet : c'est un geste discret, la latence s'y
        // voit immédiatement.
        $tab
            .dropFirst()
            .removeDuplicates()
            .sink { [weak self] _ in Task { @MainActor in await self?.reload() } }
            .store(in: &cancellables)
    }

    public var canLoadMore: Bool { tab == .mine && nextCursor != nil && !isLoading }

    public var emptyMessage: String {
        if !query.isEmpty {
            return String(localized: "story.sound.library.emptySearch",
                          defaultValue: "Aucun son ne correspond à cette recherche.", bundle: .module)
        }
        return tab == .mine
            ? String(localized: "story.sound.library.emptyMine",
                     defaultValue: "Vos sons apparaîtront ici dès que vous publierez une story avec un audio original.",
                     bundle: .module)
            : String(localized: "story.sound.library.emptyTrending",
                     defaultValue: "Aucun son public pour le moment.", bundle: .module)
    }

    /// Libellé affiché pour un son.
    ///
    /// Le discriminant est la PRÉSENCE d'un titre, pas `isAutoGenerated` : un son
    /// capturé puis nommé doit montrer son titre, et un envoi manuel dont le
    /// titre a été vidé doit retomber sur le libellé par défaut. Sans titre, on
    /// montre la date d'envoi — jamais une chaîne « Son original » venue du
    /// serveur, qui serait en français dans les sept langues.
    public static func displayTitle(for sound: APISound) -> String {
        if sound.hasAuthoredTitle { return sound.title }
        if let createdAt = sound.createdAt {
            return createdAt.formatted(date: .abbreviated, time: .shortened)
        }
        return String(localized: "story.sound.library.untitled",
                      defaultValue: "Son original", bundle: .module)
    }

    public func loadIfNeeded() async {
        guard !loadedOnce else { return }
        loadedOnce = true
        await reload()
    }

    public func reload() async {
        isLoading = true
        nextCursor = nil
        defer { isLoading = false }
        do {
            switch tab {
            case .mine:
                let page = try await service.mySounds(query: query.isEmpty ? nil : query, cursor: nil, limit: 30)
                sounds = page.sounds
                nextCursor = page.nextCursor
            case .trending:
                sounds = try await service.trendingSounds(query: query.isEmpty ? nil : query, limit: 30)
                nextCursor = nil
            }
        } catch {
            sounds = []
        }
    }

    public func loadMore() async {
        guard tab == .mine, let cursor = nextCursor, !isLoading else { return }
        isLoading = true
        defer { isLoading = false }
        do {
            let page = try await service.mySounds(query: query.isEmpty ? nil : query, cursor: cursor, limit: 30)
            sounds.append(contentsOf: page.sounds)
            nextCursor = page.nextCursor
        } catch {
            // Fin de pagination silencieuse : une page manquante ne doit pas
            // vider la liste déjà affichée.
            nextCursor = nil
        }
    }

    public func togglePreview(_ sound: APISound) {
        previewingId = previewingId == sound.id ? nil : sound.id
    }

    public func beginRename(_ sound: APISound) {
        renaming = sound
    }

    /// Applique un nouveau titre et remplace la ligne EN PLACE : recharger la
    /// liste entière ferait sauter la position de défilement au moment précis où
    /// l'utilisateur regarde ce qu'il vient de nommer.
    public func commitRename(_ sound: APISound, title: String) async {
        do {
            let updated = try await service.rename(soundId: sound.id, title: title)
            if let index = sounds.firstIndex(where: { $0.id == sound.id }) {
                sounds[index] = updated
            }
        } catch {
            // Le titre reste celui d'avant : rien n'est perdu, l'utilisateur peut
            // réessayer.
        }
        renaming = nil
    }
}
