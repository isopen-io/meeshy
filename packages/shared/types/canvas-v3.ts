import { z } from 'zod';

/** Kinds réservés (O1/S5/O10) — nomenclature connue, REFUSÉS en v1. */
export const RESERVED_KINDS = ['hashtag', 'annotation', 'interactive'] as const;
const ACTIVE_KINDS = ['text', 'media', 'sticker', 'audio', 'place', 'drawing', 'mention'] as const;

const AnchorSchema = z.discriminatedUnion('t', [
  z.object({ t: z.literal('free'), x: z.number().min(0).max(1), y: z.number().min(0).max(1) }),
  z.object({ t: z.literal('band'), edge: z.enum(['top', 'bottom']) }),
]);

const KeyframeSchema = z.object({
  time: z.number().min(0),
  x: z.number().optional(), y: z.number().optional(),
  scale: z.number().positive().optional(),
  opacity: z.number().min(0).max(1).optional(),
  volume: z.number().min(0).max(1).optional(),
  easing: z.enum(['linear', 'easeIn', 'easeOut', 'easeInOut', 'spring']).optional(),
});

const TimingSchema = z.object({
  start: z.number().min(0).optional(),
  end: z.number().min(0).optional(),
  rate: z.number().min(0.25).max(4).optional(),
  keyframes: z.array(KeyframeSchema).max(60).optional(),
}).refine((t) => t.start === undefined || t.end === undefined || t.end >= t.start, {
  // Invariant temporel : un objet ne peut sortir de la timeline AVANT d'y
  // entrer. Ne se vérifie QUE lorsque les deux bornes sont posées — une timing
  // partielle (`{ start }` seul, `{ keyframes }` seul, cf. golden v1→v3) reste
  // valide. Même registre de garantie que `transcriptionSegmentSchema`
  // (`endMs >= startMs`, itération 234) : la borne haute >= la borne basse, la
  // durée nulle (`end === start`) acceptée.
  path: ['end'],
  message: 'TIMING_END_BEFORE_START',
});

const ObjectV3Schema = z.object({
  id: z.string().min(1),
  kind: z.string().superRefine((k, ctx) => {
    if ((RESERVED_KINDS as readonly string[]).includes(k)) {
      ctx.addIssue({ code: z.ZodIssueCode.custom, message: `KIND_RESERVED:${k}` });
    } else if (!(ACTIVE_KINDS as readonly string[]).includes(k)) {
      ctx.addIssue({ code: z.ZodIssueCode.custom, message: `KIND_UNKNOWN:${k}` });
    }
  }),
  anchor: AnchorSchema,
  plane: z.enum(['bg', 'content', 'fg']),
  z: z.number().int(),
  transform: z.object({
    scale: z.number().positive(),
    rotation: z.number(),
    opacity: z.number().min(0).max(1),
  }),
  timing: TimingSchema.optional(),
  locale: z.string().min(2).max(8).optional(),
  // payload permissif PAR CONTRAT — il porte notamment, pour kind:text,
  // `translations: {lang: contenu}` (Prisme par objet, spec §C1 rév. 4/C6) :
  // le convertisseur A3 et le golden en font foi, pas une contrainte Zod.
  payload: z.record(z.string(), z.unknown()),
});

// Variante TTS d'une piste, par langue — miroir du `backgroundAudioVariants`
// racine v1 (`StoryAudioVariant` iOS : les trois clés sont NON optionnelles
// des deux côtés, un décodeur Swift synthétisé refuse une variante amputée).
const AudioVariantSchema = z.object({
  postMediaId: z.string().min(1),
  language: z.string().min(2).max(8),
  isAutoGenerated: z.boolean(),
});

const BackgroundSoundSchema = z.object({
  source: z.discriminatedUnion('t', [
    z.object({ t: z.literal('original') }),
    z.object({ t: z.literal('library'), soundId: z.string().min(1) }),
  ]),
  volume: z.number().min(0).max(1).default(1),
  bounds: z.object({ start: z.number().min(0), end: z.number().min(0) })
    // Mêmes bornes temporelles que TimingSchema : la fin du segment d'audio ne
    // peut précéder son début. Les deux bornes étant requises ici, le refine
    // est inconditionnel. Durée nulle (`end === start`) acceptée.
    .refine((b) => b.end >= b.start, { path: ['end'], message: 'BOUNDS_END_BEFORE_START' })
    .optional(),
  variants: z.array(AudioVariantSchema).max(32).optional(),
  // Sous-titres voix par langue (karaoké = Prisme audio) — logement du
  // `voiceTranscriptions` racine v1 (spec §C1 rév. 4, revue totale C7).
  transcriptions: z.array(z.object({
    language: z.string().min(2).max(8),
    content: z.string(),
  })).optional(),
});

const SceneV3Schema = z.object({
  id: z.string().min(1),
  objects: z.array(ObjectV3Schema).max(60),
  opening: z.record(z.string(), z.unknown()).optional(),
  closing: z.record(z.string(), z.unknown()).optional(),
  clipTransitions: z.array(z.record(z.string(), z.unknown())).max(30).optional(),
  timelineDuration: z.number().positive().optional(),
  // Empreinte du canvas composite — le placeholder que quatre surfaces
  // affichent avant l'arrivée du média. Même plafond que la clé v1 homonyme.
  thumbHash: z.string().min(1).max(100).optional(),
  // Ratio du PORTEUR d'origine (largeur/hauteur), quand la scène provient d'une
  // conversion v1 (révision de S8).
  //
  // S8 gravait la disparition de `canvasAspectRatio` — « le porteur garde son
  // propre ratio ». L'argument vaut pour la LECTURE : un lecteur peint une
  // scène 9:16 et le porteur letterboxe lui-même. Il ne vaut pas pour
  // l'ÉDITION. `remapFreeAnchor` est AFFINE (`y' = top + y·h`, où
  // `h = 9/16 ÷ carrierAspect` et `top = (1−h)/2`) : elle est donc inversible —
  // mais seulement si l'on sait encore ce que valait le porteur. Jeté, il
  // rendait la conversion à sens unique, et rouvrir un ancien post recadrait
  // définitivement ses objets (sur du 16:9, `y = 0,90` devenait `0,6266`).
  //
  // `StoryDraftStore` avait déjà dû le repersister hors document, par
  // diapositive, pour les seuls brouillons. Le loger ICI cesse d'industrialiser
  // ce pansement et rend au document sa source de vérité unique.
  //
  // OPTIONNEL et ADDITIF : un document v3 natif n'en a pas — il n'a jamais eu
  // d'autre porteur que sa scène. Aucun lecteur existant n'est cassé.
  carrierAspect: z.number().positive().finite().optional(),
});

export const CanvasV3Schema = z.object({
  v: z.literal(3),
  // O3 — `scenes` absent tant qu'aucun objet visuel : jamais de cadre vide.
  // Présent, il porte au moins une scène.
  scenes: z.array(SceneV3Schema).min(1).max(10).optional(),
  sound: BackgroundSoundSchema.optional(),
});

export type CanvasV3 = z.infer<typeof CanvasV3Schema>;
export type SceneV3 = z.infer<typeof SceneV3Schema>;
export type ObjectV3 = z.infer<typeof ObjectV3Schema>;
export type BackgroundSoundV3 = z.infer<typeof BackgroundSoundSchema>;
export type KeyframeV3 = z.infer<typeof KeyframeSchema>;
export type AudioVariantV3 = z.infer<typeof AudioVariantSchema>;
