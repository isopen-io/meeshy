package me.meeshy.sdk.model.composer.sound

import kotlinx.serialization.Serializable

/**
 * Un son de la bibliothèque tel que la passerelle le projette — miroir d'`APISound` (iOS) et de `toDTO`
 * (`services/gateway/src/routes/posts/sounds.ts`). `contentHash` n'en fait JAMAIS partie : c'est un oracle de
 * possession de fichier.
 *
 * Tous les champs hors `id` et `fileUrl` ont un défaut : une app plus récente que sa passerelle (ou l'inverse)
 * ne doit pas faire échouer la LISTE entière sur un compteur décoratif.
 */
@Serializable
data class ApiSound(
    val id: String,
    /** Vide pour un son CAPTÉ non nommé : le libellé se compose côté client, jamais en base. */
    val title: String = "",
    val fileUrl: String,
    val durationMs: Long? = null,
    val waveform: List<Float> = emptyList(),
    /** Compte des PISTES (classement « Tendances ») — ne jamais l'afficher, voir [postCount]. */
    val usageCount: Int = 0,
    /** Publications distinctes et visibles qui utilisent ce son : le nombre qui s'affiche. */
    val postCount: Int = 0,
    val playCount: Int = 0,
    val isPublic: Boolean = true,
    val isAutoGenerated: Boolean = false,
    val coverUrl: String? = null,
    val coverThumbHash: String? = null,
    val coverColor: String? = null,
    val createdAt: String? = null,
    val uploader: ApiSoundUploader? = null,
) {
    /** `displayName` s'il existe, sinon `@pseudo` ; `null` sans auteur. */
    val authorLabel: String?
        get() {
            val author = uploader ?: return null
            return author.displayName?.takeIf { it.isNotEmpty() } ?: "@${author.username}"
        }

    /** Le son porte-t-il un titre donné par son auteur ? C'est CETTE question, pas `isAutoGenerated`, qui décide. */
    val hasAuthoredTitle: Boolean get() = title.isNotBlank()
}

@Serializable
data class ApiSoundUploader(
    val id: String,
    val username: String,
    val displayName: String? = null,
    val avatar: String? = null,
)

/** Réponse de `DELETE /sounds/:id` : le retrait est LOGIQUE, les publications existantes le jouent toujours (#9848). */
@Serializable
data class SoundRemoval(
    val id: String,
    val deletedAt: String? = null,
    val postCount: Int = 0,
)

/** Corps de `PATCH /sounds/:id` — un titre vide retire le titre. */
@Serializable
data class RenameSoundRequest(val title: String)
