/**
 * The ten tabs of the emoji picker, in display order — port of iOS
 * `EmojiGridCategory` (EmojiPickerSheet.swift). [key] is the stable storage /
 * saved-state identity (iOS `rawValue`); the localized label and the tab icon
 * belong to the UI layer, which maps over this enum exhaustively.
 */
enum class EmojiCategoryId(val key: String) {
    RECENT("recent"),
    SMILEYS("smileys"),
    PEOPLE("people"),
    ANIMALS("animals"),
    FOOD("food"),
    ACTIVITIES("activities"),
    TRAVEL("travel"),
    OBJECTS("objects"),
    SYMBOLS("symbols"),
    FLAGS("flags"),
    ;

    companion object {
        fun fromKey(key: String?): EmojiCategoryId? = entries.firstOrNull { it.key == key }
    }
}

/**
 * One tab of the picker. [EmojiCategoryId.RECENT] carries no catalog content:
 * its grid is the user's history, assembled by [EmojiPickerPresenter].
 */
data class EmojiCategory(
    val id: EmojiCategoryId,
    val emojis: List<String>,
)

