package me.meeshy.sdk.model.composer.sound

import java.text.Normalizer
import java.time.Instant

enum class SoundShelfTab { MINE, TRENDING }

/** Ce que la ligne d'un son dit en titre — le texte se compose côté UI (locale du lecteur). */
sealed interface SoundTitle {
    data class Authored(val text: String) : SoundTitle
    data class UploadedAt(val epochMillis: Long) : SoundTitle
    data object Original : SoundTitle
}

/** Ce que la confirmation de retrait doit dire AVANT le geste. */
sealed interface SoundRemovalNotice {
    data object Unused : SoundRemovalNotice
    data class StillPlayed(val postCount: Int) : SoundRemovalNotice
}

enum class SoundShelfEmpty { NoMatch, NoneMine, NoneTrending }

/**
 * Les règles PURES de l'étagère des sons — miroir de `SoundLibraryPickerModel` (iOS). Aucune dépendance Android :
 * ce que la vue montre se décide ici, éprouvable sans écran.
 */
object SoundShelfLaw {

    /**
     * Le discriminant est la PRÉSENCE d'un titre, pas `isAutoGenerated`. Sans titre on montre la date d'envoi —
     * jamais une chaîne « Son original » venue du serveur, qui serait dans une seule langue.
     */
    fun title(sound: ApiSound): SoundTitle {
        if (sound.hasAuthoredTitle) return SoundTitle.Authored(sound.title.trim())
        val millis = epochMillis(sound.createdAt) ?: return SoundTitle.Original
        return SoundTitle.UploadedAt(millis)
    }

    /** La date sous le titre : seulement dans « Mes sons » et seulement sur un son NOMMÉ (sinon elle EST le titre). */
    fun secondaryDateMillis(sound: ApiSound, isMine: Boolean): Long? {
        if (!isMine || !sound.hasAuthoredTitle) return null
        return epochMillis(sound.createdAt)
    }

    fun canRemove(tab: SoundShelfTab): Boolean = tab == SoundShelfTab.MINE

    fun canRename(tab: SoundShelfTab): Boolean = tab == SoundShelfTab.MINE

    /** Seule la bibliothèque personnelle se pagine par curseur ; « Tendances » est une liste bornée. */
    fun pages(tab: SoundShelfTab): Boolean = tab == SoundShelfTab.MINE

    fun empty(tab: SoundShelfTab, query: String): SoundShelfEmpty = when {
        query.isNotEmpty() -> SoundShelfEmpty.NoMatch
        tab == SoundShelfTab.MINE -> SoundShelfEmpty.NoneMine
        else -> SoundShelfEmpty.NoneTrending
    }

    fun removalNotice(sound: ApiSound): SoundRemovalNotice =
        if (sound.postCount > 0) SoundRemovalNotice.StillPlayed(sound.postCount) else SoundRemovalNotice.Unused

    /** Filtre local sur le titre ET le pseudo ET le nom affiché — même règle que la recherche serveur de « Tendances ». */
    fun filter(sounds: List<ApiSound>, query: String?): List<ApiSound> {
        val needle = fold(query?.trim().orEmpty())
        if (needle.isEmpty()) return sounds
        return sounds.filter { s ->
            listOf(s.title, s.uploader?.username.orEmpty(), s.uploader?.displayName.orEmpty())
                .any { fold(it).contains(needle) }
        }
    }

    /** Un renommage remplace la ligne EN PLACE : recharger la liste ferait sauter le défilement. */
    fun replacing(sounds: List<ApiSound>, updated: ApiSound): List<ApiSound> =
        sounds.map { if (it.id == updated.id) updated else it }

    /** Un retrait refusé remet la ligne à SA place — pas en tête, pas en fin ; déjà présente, rien ne change. */
    fun restoring(sounds: List<ApiSound>, snapshot: ApiSound, index: Int): List<ApiSound> {
        if (sounds.any { it.id == snapshot.id }) return sounds
        return sounds.toMutableList().apply { add(index.coerceIn(0, size), snapshot) }
    }

    private fun fold(value: String): String =
        Normalizer.normalize(value, Normalizer.Form.NFD).replace(MARKS, "").lowercase()

    private fun epochMillis(iso: String?): Long? =
        iso?.let { runCatching { Instant.parse(it).toEpochMilli() }.getOrNull() }

    private val MARKS = Regex("\\p{Mn}+")
}
