import type { InfiniteData, QueryClient } from '@tanstack/react-query';
import * as z from 'zod/mini';
import * as soundsEndpoints from '@meeshy/shared/api/endpoints/sounds';

import { unwrap } from './client';
import type { DataSource } from './config';
import type { ApiResult, HttpTransport } from './http';

/**
 * **LE PORT DE « MES SONS »** (#9848) — `GET sounds.mine` (les sons dont le
 * lecteur est l'auteur : téléversés, ou extraits de ses vidéos) et
 * `DELETE sounds.byId` (`services/gateway/src/routes/posts/sounds.ts`), miroir
 * de `SoundLibraryService` côté iOS.
 *
 * **RETIRER N'EST PAS EFFACER.** La passerelle pose `deletedAt` : le son quitte
 * toutes les listes et ne s'ajoute plus à une nouvelle publication, mais les
 * publications DÉJÀ parues continuent de le jouer — celles des autres
 * comprises. D'où le compteur `postCount` que l'écran montre AVANT la
 * confirmation, et que la réponse actualise.
 *
 * **LE CURSEUR EST UNE DATE ISO** (`createdAt` du dernier son servi), relue
 * telle quelle : la réécrire perdrait les millisecondes et la page suivante
 * répéterait la dernière ligne (même piège que #6609 côté iOS).
 */

export type MySoundsDeps = { readonly source: DataSource; readonly transport: HttpTransport };

/** La page d'iOS (`SoundLibraryPickerModel`, `limit: 30`) ; la route borne à 50. */
export const MY_SOUNDS_PAGE_SIZE = 30;

/** UNE clé, sans paramètre : ce corpus est celui du lecteur connecté. */
export const MY_SOUNDS_QUERY_KEY = ['sounds', 'mine'] as const;

/**
 * Le corpus ne bouge que par un geste de son auteur (publier, retirer, nommer),
 * qui écrit déjà le cache. Une minute suffit à ne pas relire au moindre
 * remontage, sans figer une liste qu'une publication depuis un autre appareil
 * aurait allongée.
 */
const MY_SOUNDS_STALE_TIME = 60_000;

export type MySound = {
  readonly id: string;
  /** Vide pour un son capturé jamais nommé : l'écran compose « Son original ». */
  readonly title: string;
  readonly durationMs: number | null;
  /** Publications PUBLIQUES qui l'utilisent — le même ensemble que la page du son. */
  readonly postCount: number;
  readonly playCount: number;
  readonly isAutoGenerated: boolean;
  readonly coverUrl: string | null;
  readonly coverColor: string | null;
  readonly createdAt: string | null;
};

export type MySoundsPage = { readonly sounds: readonly MySound[]; readonly nextCursor: string | null };
export type MySoundsData = InfiniteData<MySoundsPage, unknown>;

const count = z.optional(z.nullable(z.number()));
const text = z.optional(z.nullable(z.string()));

const WireSound = z.object({
  id: z.string(),
  title: text,
  durationMs: count,
  postCount: count,
  playCount: count,
  isAutoGenerated: z.optional(z.nullable(z.boolean())),
  coverUrl: text,
  coverColor: text,
  createdAt: text,
});

export function decodeMySound(raw: unknown): MySound | null {
  const parsed = WireSound.safeParse(raw);
  if (!parsed.success || parsed.data.id === '') return null;
  const wire = parsed.data;
  return {
    id: wire.id,
    title: wire.title ?? '',
    durationMs: wire.durationMs ?? null,
    postCount: wire.postCount ?? 0,
    playCount: wire.playCount ?? 0,
    isAutoGenerated: wire.isAutoGenerated ?? false,
    coverUrl: wire.coverUrl ?? null,
    coverColor: wire.coverColor ?? null,
    createdAt: wire.createdAt ?? null,
  };
}

const WirePagination = z.object({ hasMore: z.optional(z.boolean()), nextCursor: z.optional(z.nullable(z.string())) });

const nextCursorOf = (pagination: unknown): string | null => {
  const parsed = WirePagination.safeParse(pagination);
  if (!parsed.success || parsed.data.hasMore !== true) return null;
  const cursor = parsed.data.nextCursor ?? null;
  return cursor === null || cursor === '' ? null : cursor;
};

const minePath = (cursor: string | null): string => {
  const query = new URLSearchParams({ limit: String(MY_SOUNDS_PAGE_SIZE) });
  if (cursor !== null) query.set('cursor', cursor);
  return `${soundsEndpoints.mine}?${query.toString()}`;
};

export async function loadMySounds(
  params: MySoundsDeps & { readonly cursor: string | null; readonly signal?: AbortSignal },
): Promise<ApiResult<MySoundsPage>> {
  if (__FIXTURES__ && params.source === 'fixtures') {
    return { ok: true, status: 200, data: { sounds: [], nextCursor: null } };
  }
  const result = await params.transport.request<unknown>({
    method: 'GET',
    path: minePath(params.cursor),
    ...(params.signal === undefined ? {} : { signal: params.signal }),
  });
  if (!result.ok) return result;
  const sounds = (Array.isArray(result.data) ? result.data : []).flatMap((raw) => {
    const decoded = decodeMySound(raw);
    return decoded === null ? [] : [decoded];
  });
  return { ...result, data: { sounds, nextCursor: nextCursorOf(result.pagination) } };
}

type PageContext = { readonly pageParam: string | null; readonly signal?: AbortSignal };

export function mySoundsQueryOptions(deps: MySoundsDeps) {
  return {
    queryKey: MY_SOUNDS_QUERY_KEY,
    staleTime: MY_SOUNDS_STALE_TIME,
    initialPageParam: null as string | null,
    queryFn: async ({ pageParam, signal }: PageContext) =>
      unwrap(await loadMySounds({ ...deps, cursor: pageParam, ...(signal === undefined ? {} : { signal }) })),
    getNextPageParam: (page: MySoundsPage) => page.nextCursor ?? undefined,
  };
}

export const flattenMySounds = (data: MySoundsData | undefined): readonly MySound[] =>
  data?.pages.flatMap((page) => page.sounds) ?? [];

const WireRemoval = z.object({ postCount: z.optional(z.nullable(z.number())) });

/**
 * `DELETE sounds.byId` — IDEMPOTENT côté passerelle : un second appel (double
 * geste, rejeu) rend le même état et garde la date du premier retrait.
 */
export async function removeSound(deps: MySoundsDeps, soundId: string): Promise<ApiResult<{ readonly postCount: number }>> {
  if (__FIXTURES__ && deps.source === 'fixtures') {
    return { ok: true, status: 200, data: { postCount: 0 } };
  }
  const result = await deps.transport.request<unknown>({ method: 'DELETE', path: soundsEndpoints.byId(soundId) });
  if (!result.ok) return result;
  const parsed = WireRemoval.safeParse(result.data);
  return { ...result, data: { postCount: parsed.success ? parsed.data.postCount ?? 0 : 0 } };
}

export function withoutSound(data: MySoundsData | undefined, soundId: string): MySoundsData | undefined {
  if (data === undefined) return undefined;
  return { ...data, pages: data.pages.map((page) => ({ ...page, sounds: page.sounds.filter((s) => s.id !== soundId) })) };
}

/**
 * Les sons qui PRÉCÈDENT la ligne retirée, du plus proche au plus lointain :
 * c'est par eux qu'on la remet à sa place. Un indice ne suffit pas — un autre
 * son retiré pendant l'aller-retour décalerait tout ce qui le suit.
 */
const predecessorsOf = (data: MySoundsData | undefined, soundId: string): readonly string[] | null => {
  const ids = flattenMySounds(data).map((s) => s.id);
  const at = ids.indexOf(soundId);
  return at < 0 ? null : ids.slice(0, at).reverse();
};

/**
 * Remet UNE ligne juste après le plus proche de ses prédécesseurs encore
 * présent (en tête s'il n'en reste aucun) — jamais l'instantané entier : un
 * autre son retiré pendant l'aller-retour ne doit pas revenir avec elle.
 */
function withSoundRestored(
  data: MySoundsData | undefined,
  sound: MySound,
  predecessors: readonly string[],
): MySoundsData | undefined {
  if (data === undefined || data.pages.length === 0 || flattenMySounds(data).some((s) => s.id === sound.id)) return data;
  const present = new Set(flattenMySounds(data).map((s) => s.id));
  const anchor = predecessors.find((id) => present.has(id)) ?? null;
  const anchorPage = anchor === null ? 0 : data.pages.findIndex((page) => page.sounds.some((s) => s.id === anchor));
  return {
    ...data,
    pages: data.pages.map((page, pageIndex) => {
      if (pageIndex !== anchorPage) return page;
      const at = anchor === null ? 0 : page.sounds.findIndex((s) => s.id === anchor) + 1;
      return { ...page, sounds: [...page.sounds.slice(0, at), sound, ...page.sounds.slice(at)] };
    }),
  };
}

export type SoundRemovalDeps = MySoundsDeps & {
  readonly queryClient: QueryClient;
  readonly isOnline: () => boolean;
};

export type SoundRemovalOutcome = 'done' | 'offline' | 'failed';

/**
 * Retrait OPTIMISTE : la ligne part au geste, le réseau confirme ensuite, et
 * un refus la remet à SA place. Hors ligne, rien ne part : le retour en
 * arrière supposerait une réponse qu'aucun réseau ne servirait.
 */
export async function performRemoveSound({
  sound,
  deps,
}: {
  readonly sound: MySound;
  readonly deps: SoundRemovalDeps;
}): Promise<SoundRemovalOutcome> {
  if (!deps.isOnline()) return 'offline';
  const predecessors = predecessorsOf(deps.queryClient.getQueryData<MySoundsData>(MY_SOUNDS_QUERY_KEY), sound.id);
  deps.queryClient.setQueryData<MySoundsData>(MY_SOUNDS_QUERY_KEY, (data) => withoutSound(data, sound.id));
  const result = await removeSound(deps, sound.id);
  if (result.ok) return 'done';
  if (predecessors !== null) {
    deps.queryClient.setQueryData<MySoundsData>(MY_SOUNDS_QUERY_KEY, (data) => withSoundRestored(data, sound, predecessors));
  }
  return 'failed';
}
