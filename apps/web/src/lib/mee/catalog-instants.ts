/**
 * LES INSTANTS (#9034) — cent stickers DYNAMIQUES. Chacun écrit, au moment
 * de l'envoi, ce que l'utilisateur a saisi : la météo et le lieu, l'heure et
 * un mot, le lieu et un mot, ou un message seul. Rien saisi ⇒ la valeur par
 * défaut du sticker, pour qu'il ne parte jamais vide.
 *
 * Le repère : le personnage est réduit (corps en (100, 90), bec vers
 * (148, 105), ailes en (65, 82) et (135, 82)) et laisse le bas de la scène
 * au bandeau (y 148 → 194).
 */

type Base = Entry & { readonly c: MeeCharacter; readonly pose: BirdPose; readonly back?: string; readonly front?: string };

const meteo = (e: Base & { readonly weather: string; readonly tint?: string }): MeeSticker =>
  instant('meteo', e.c, {
    ...e,
    slots: ['weather', 'place'],
    defaults: { weather: e.weather },
    back: e.back ?? '',
    front: (s: MeeSlots) => `${e.front ?? ''}${band(s.weather ?? e.weather, s.place, { fill: e.tint ?? '#e0f2fe' })}`,
  });

const moment = (e: Base & { readonly time: string; readonly message: string; readonly tint?: string }): MeeSticker =>
  instant('moment', e.c, {
    ...e,
    slots: ['time', 'message'],
    defaults: { time: e.time, message: e.message },
    back: e.back ?? '',
    front: (s: MeeSlots) => `${e.front ?? ''}${band(s.time ?? e.time, s.message, { fill: e.tint ?? '#fef3c7' })}`,
  });

const lieu = (e: Base & { readonly place: string; readonly message?: string; readonly tint?: string }): MeeSticker =>
  instant('lieu', e.c, {
    ...e,
    slots: ['place', 'message'],
    defaults: { place: e.place, ...(e.message !== undefined ? { message: e.message } : {}) },
    back: e.back ?? '',
    front: (s: MeeSlots) => `${e.front ?? ''}${at(26, 160, P.pin(e.c === 'mee' ? '#e11d48' : '#7c3aed'), { s: 0.55 })}${band(s.place ?? e.place, s.message, { fill: e.tint ?? '#dcfce7' })}`,
  });

/** Un message porté par la scène elle-même — un cœur, une lettre, une banderole. */
const message = (e: Base & { readonly text: string; readonly carry: (text: string) => string; readonly at?: string }): MeeSticker =>
  instant('message', e.c, {
    ...e,
    slots: ['message'],
    defaults: { message: e.text },
    back: e.back ?? '',
    front: (s: MeeSlots) => `${e.front ?? ''}${e.carry(s.message ?? e.text)}`,
    ...(e.at !== undefined ? { at: e.at } : {}),
  });

