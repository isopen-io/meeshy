const TEXTS: Readonly<Record<AdminLanguage, Texts>> = { fr, en, es, pt };

const PLACEHOLDER = /\{(\w+)\}/g;

export const lensModerationText = (language: AdminLanguage, key: LensModerationTextKey, params?: Readonly<Record<string, string>>): string =>
  params === undefined ? TEXTS[language][key] : TEXTS[language][key].replace(PLACEHOLDER, (whole, name: string) => params[name] ?? whole);

/** Témoins seulement. */
export const lensModerationTextKeysOf = (language: AdminLanguage): readonly string[] => Object.keys(TEXTS[language]);
