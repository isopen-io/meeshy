describe('la matrice est celle d’une implémentation indépendante', () => {
  for (const reference of REFERENCES) {
    test(reference.name, () => {
      const matrix = encodeQr(reference.text);
      expect(matrix?.version).toBe(reference.version);
      expect(matrix?.size).toBe(reference.rows.length);
      expect(rowsOf(matrix)).toEqual([...reference.rows]);
    });
  }
});

describe('la version se choisit seule', () => {
  test('la plus petite qui porte le texte en correction M : 26 octets tiennent en v2, 27 passent en v3', () => {
    expect(encodeQr('x'.repeat(14))?.version).toBe(1);
    expect(encodeQr('x'.repeat(15))?.version).toBe(2);
    expect(encodeQr('x'.repeat(26))?.version).toBe(2);
    expect(encodeQr('x'.repeat(27))?.version).toBe(3);
    expect(encodeQr('x'.repeat(27))?.size).toBe(29);
  });

  test('les octets comptent, pas les caractères', () => {
    expect(encodeQr('é'.repeat(7))?.version).toBe(1);
    expect(encodeQr('é'.repeat(8))?.version).toBe(2);
  });

  test('un plafond de version : au-delà, pas de matrice plutôt qu’une matrice illisible', () => {
    expect(encodeQr('x'.repeat(27), { maxVersion: 3 })?.version).toBe(3);
    expect(encodeQr('x'.repeat(27), { maxVersion: 2 })).toBeNull();
    expect(encodeQr('x'.repeat(3000))).toBeNull();
  });
});

describe('la forme rendue', () => {
  test('un carré de `size` rangées de `size` modules, et le masque retenu', () => {
    const matrix = encodeQr('https://meeshy.me/r/Ab3dE9');
    expect(matrix?.modules).toHaveLength(25);
    for (const row of matrix?.modules ?? []) expect(row).toHaveLength(25);
    expect(matrix?.mask).toBeGreaterThanOrEqual(0);
    expect(matrix?.mask).toBeLessThanOrEqual(7);
  });

  test('le même texte rend la même matrice', () => {
    expect(encodeQr('https://meeshy.me/r/Ab3dE9')).toEqual(encodeQr('https://meeshy.me/r/Ab3dE9'));
  });
});
