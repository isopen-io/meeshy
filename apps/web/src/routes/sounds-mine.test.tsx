import { act } from 'react';
import { QueryClientProvider } from '@tanstack/react-query';
import { afterAll, afterEach, beforeAll, describe, expect, test } from 'bun:test';

import type { ApiResult, HttpRequest } from '@/lib/api/http';
import { MY_SOUNDS_QUERY_KEY, type MySound, type MySoundsData } from '@/lib/api/my-sounds';
import { appQueryClient } from '@/lib/api/query-client';
import { loadInterfaceCatalog } from '@/lib/i18n-catalog';
import { createActMounter } from '@/test-support/act-mount';
import { ensureHappyDomRegistered, releaseHappyDomIfRegistered } from '@/test-support/happy-dom-environment';
import { scriptedTransport } from '@/test-support/scripted-transport';

import { SoundsMineView, soundRemovalBody, soundRowTitle } from './sounds-mine';

/**
 * **« MES SONS », MONTÉ POUR DE VRAI** (#9848) — la liste servie par le cache
 * (jamais un squelette sur un cache plein), le geste de retrait, la
 * confirmation qui dit combien de publications jouent encore le son, le
 * retrait optimiste et son retour arrière à SA place.
 */
const globals = globalThis as typeof globalThis & { IS_REACT_ACT_ENVIRONMENT?: boolean };

beforeAll(async () => {
  ensureHappyDomRegistered();
  globals.IS_REACT_ACT_ENVIRONMENT = true;
  await loadInterfaceCatalog('fr');
});

afterAll(async () => {
  delete globals.IS_REACT_ACT_ENVIRONMENT;
  await releaseHappyDomIfRegistered();
});

const mounter = createActMounter();

const setOnline = (online: boolean): void => {
  Object.defineProperty(window.navigator, 'onLine', { configurable: true, get: () => online });
  window.dispatchEvent(new Event(online ? 'online' : 'offline'));
};

afterEach(() => {
  mounter.unmountAll();
  appQueryClient.clear();
  setOnline(true);
});

const sound = (id: string, overrides: Partial<MySound> = {}): MySound => ({
  id,
  title: `Son ${id}`,
  durationMs: 4000,
  postCount: 0,
  playCount: 0,
  isAutoGenerated: false,
  coverUrl: null,
  coverColor: null,
  createdAt: '2026-10-01T10:00:00.000Z',
  ...overrides,
});

const seed = (...sounds: readonly MySound[]): void => {
  const data: MySoundsData = { pages: [{ sounds, nextCursor: null }], pageParams: [null] };
  appQueryClient.setQueryData(MY_SOUNDS_QUERY_KEY, data);
};

/** Une passerelle dont le témoin décide QUAND et COMMENT elle répond. */
const deferredGateway = () => {
  const { transport, calls } = scriptedTransport({});
  let answer: (ok: boolean) => void = () => undefined;
  transport.request = <T,>(request: HttpRequest) => {
    (calls() as HttpRequest[]).push(request);
    return new Promise<ApiResult<T>>((resolve) => {
      answer = (ok) =>
        resolve(ok ? { ok: true, status: 200, data: { postCount: 0 } as T } : { ok: false, status: 500, error: 'boom' });
    });
  };
  return {
    transport,
    calls,
    answer: async (ok: boolean): Promise<void> => {
      await act(async () => {
        answer(ok);
      });
      await mounter.settle();
    },
  };
};

async function mountScreen(transport = deferredGateway().transport): Promise<HTMLElement> {
  const host = await mounter.mount(
    <QueryClientProvider client={appQueryClient}>
      <SoundsMineView transport={transport} />
    </QueryClientProvider>,
  );
  await mounter.settle();
  return host;
}

const rows = (host: HTMLElement): readonly string[] =>
  [...host.querySelectorAll('[data-my-sounds-list] li[data-my-sound]')].map((li) => li.getAttribute('data-my-sound') ?? '');

const askRemoval = async (host: HTMLElement, id: string): Promise<void> => {
  await mounter.click(host.querySelector<HTMLButtonElement>(`li[data-my-sound="${id}"] [data-my-sound-remove]`));
};

const confirm = async (host: HTMLElement): Promise<void> => {
  await mounter.click(host.querySelector<HTMLButtonElement>('[data-confirm-dialog="my-sound-remove"] [data-confirm="confirm"]'));
};

describe('les libellés', () => {
  test('un son capturé jamais nommé se lit « Son original », un son nommé garde son titre', () => {
    expect(soundRowTitle(sound('a', { title: '' }), 'fr')).toBe('Son original');
    expect(soundRowTitle(sound('a', { title: 'Pluie' }), 'fr')).toBe('Pluie');
  });

  test('la confirmation dit, AVANT le geste, combien de publications le jouent encore', () => {
    expect(soundRemovalBody(0, 'fr')).not.toContain('continuer');
    expect(soundRemovalBody(1, 'fr')).toContain('1 publication l’utilise encore');
    expect(soundRemovalBody(3, 'fr')).toContain('3 publications l’utilisent encore');
  });
});

describe('SoundsMineView — les états', () => {
  test('LISTE : servie par le cache, sans squelette', async () => {
    seed(sound('a'), sound('b', { title: '', postCount: 2 }));
    const host = await mountScreen();
    expect(rows(host)).toEqual(['a', 'b']);
    expect(host.querySelector('li[data-my-sound="b"]')?.textContent).toContain('Son original');
    expect(host.querySelector('li[data-my-sound="b"]')?.textContent).toContain('2 publications');
  });

  test('VIDE : un état qui dit d’où viennent les sons, jamais un écran blanc', async () => {
    seed();
    const host = await mountScreen();
    expect(host.querySelector('[data-my-sounds-empty]')?.textContent).toContain('Aucun son dans votre bibliothèque');
  });

  test('le retour mène aux réglages, nommé, à une cible de 44', async () => {
    seed(sound('a'));
    const host = await mountScreen();
    const back = host.querySelector('a[aria-label="Retour aux réglages"]');
    expect(back?.getAttribute('href')).toBe('/settings');
    expect(back?.className).toContain('size-11');
  });
});

describe('SoundsMineView — retirer, optimiste', () => {
  test('le geste ouvre une confirmation qui annonce les publications, et rien ne part encore', async () => {
    seed(sound('a'), sound('b', { postCount: 3 }));
    const gateway = deferredGateway();
    const host = await mountScreen(gateway.transport);

    await askRemoval(host, 'b');

    const dialog = host.querySelector('[data-confirm-dialog="my-sound-remove"]');
    expect(dialog?.textContent).toContain('Retirer ce son de votre bibliothèque ?');
    expect(dialog?.textContent).toContain('3 publications l’utilisent encore');
    expect(gateway.calls()).toHaveLength(0);
    expect(rows(host)).toEqual(['a', 'b']);
  });

  test('confirmer retire la rangée AVANT la réponse, en DELETE sur l’adresse du son', async () => {
    seed(sound('a'), sound('b'), sound('c'));
    const gateway = deferredGateway();
    const host = await mountScreen(gateway.transport);

    await askRemoval(host, 'b');
    await confirm(host);

    expect(rows(host)).toEqual(['a', 'c']);
    expect(host.querySelectorAll('[data-confirm-dialog="my-sound-remove"]').length).toBe(0);
    expect(gateway.calls().map((c) => `${c.method} ${c.path}`)).toEqual(['DELETE /api/v1/sounds/b']);

    await gateway.answer(true);
    expect(rows(host)).toEqual(['a', 'c']);
    expect(host.querySelector('[data-my-sounds-announce]')?.textContent).toBe('Son retiré de votre bibliothèque');
  });

  test('un refus RAMÈNE la rangée à sa place et le DIT', async () => {
    seed(sound('a'), sound('b'), sound('c'));
    const gateway = deferredGateway();
    const host = await mountScreen(gateway.transport);

    await askRemoval(host, 'b');
    await confirm(host);
    await gateway.answer(false);

    expect(rows(host)).toEqual(['a', 'b', 'c']);
    const annonce = host.querySelector('[data-my-sounds-announce]');
    expect(annonce?.textContent).toBe('Le son n’a pas pu être retiré. Réessayez.');
    expect(annonce?.getAttribute('data-announce-tone')).toBe('error');
  });

  test('annuler ne retire rien', async () => {
    seed(sound('a'));
    const gateway = deferredGateway();
    const host = await mountScreen(gateway.transport);
    await askRemoval(host, 'a');
    await mounter.click(host.querySelector<HTMLButtonElement>('[data-confirm-dialog="my-sound-remove"] [data-confirm="cancel"]'));
    expect(rows(host)).toEqual(['a']);
    expect(gateway.calls()).toHaveLength(0);
  });
});

describe('SoundsMineView — hors ligne, l’écran le dit AVANT le geste', () => {
  test('« Retirer » est éteint, un bandeau dit pourquoi, et rien ne part', async () => {
    seed(sound('a'));
    setOnline(false);
    const gateway = deferredGateway();
    const host = await mountScreen(gateway.transport);

    expect(host.querySelector('[data-my-sounds-offline]')?.textContent).toContain('Hors ligne');
    const button = host.querySelector<HTMLButtonElement>('li[data-my-sound="a"] [data-my-sound-remove]');
    expect(button?.disabled).toBe(true);
    await mounter.click(button ?? null);
    expect(host.querySelectorAll('[data-confirm-dialog="my-sound-remove"]').length).toBe(0);
    expect(gateway.calls()).toHaveLength(0);
  });
});
