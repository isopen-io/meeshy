import { describe, it, expect } from '@jest/globals';
import { canvasReferencedMediaIds, withCanvasMedia } from '../canvasMediaClaims';

const A = 'aaaaaaaaaaaaaaaaaaaaaaaa';
const B = 'bbbbbbbbbbbbbbbbbbbbbbbb';
const C = 'cccccccccccccccccccccccc';
const D = 'dddddddddddddddddddddddd';

const object = (kind: string, payload: Record<string, unknown>) => ({
  id: `${kind}-${Math.random()}`, kind, plane: 'content', z: 0,
  anchor: { t: 'free', x: 0.5, y: 0.5 },
  transform: { scale: 1, rotation: 0, opacity: 1 },
  payload,
});

const canvas = (scenes: Array<Array<ReturnType<typeof object>>>, sound?: Record<string, unknown>) => ({
  v: 3,
  scenes: scenes.map((objects, i) => ({ id: `s${i}`, objects })),
  ...(sound ? { sound } : {}),
});

describe('canvasReferencedMediaIds', () => {
  it('test_nonCanvasBlob_returnsEmpty', () => {
    expect(canvasReferencedMediaIds(undefined)).toEqual([]);
    expect(canvasReferencedMediaIds({ audioPlayerObjects: [{ postMediaId: A }] })).toEqual([]);
  });

  it('test_everySceneAndEveryKind_areRead_includingAudioTracks', () => {
    const blob = canvas([
      [object('media', { postMediaId: A }), object('audio', { postMediaId: B })],
      [object('media', { mediaId: C })],
    ]);
    expect(canvasReferencedMediaIds(blob)).toEqual([A, B, C]);
  });

  it('test_ttsVariantsOfTheSceneSound_areReferencedToo', () => {
    const blob = canvas([[object('media', { postMediaId: A })]], {
      source: { t: 'original' },
      variants: [{ postMediaId: D, language: 'en', isAutoGenerated: true }],
    });
    expect(canvasReferencedMediaIds(blob)).toEqual([A, D]);
  });

  it('test_duplicatesAndMalformedIds_areDropped', () => {
    const blob = canvas([[
      object('media', { postMediaId: A, mediaId: A }),
      object('audio', { postMediaId: '' }),
      object('media', { postMediaId: 42 }),
      object('media', { postMediaId: '../../etc/passwd' }),
    ]]);
    expect(canvasReferencedMediaIds(blob)).toEqual([A]);
  });
});

describe('withCanvasMedia', () => {
  it('test_requestIdsKeepTheirOrder_canvasOnlyIdsAreAppended', () => {
    const blob = canvas([[object('media', { postMediaId: B }), object('audio', { postMediaId: C })]]);
    expect(withCanvasMedia([A, B], blob)).toEqual([A, B, C]);
  });

  it('test_noRequestIds_butCanvasMedia_returnsTheCanvasIds', () => {
    const blob = canvas([[object('audio', { postMediaId: C })]]);
    expect(withCanvasMedia(undefined, blob)).toEqual([C]);
  });

  it('test_nothingAnywhere_keepsUndefined', () => {
    expect(withCanvasMedia(undefined, undefined)).toBeUndefined();
    expect(withCanvasMedia([], undefined)).toEqual([]);
  });

  it('test_edit_mediaTheCanvasAlreadyLinked_isNotReclaimed', () => {
    const blob = canvas([[object('media', { postMediaId: A }), object('audio', { postMediaId: B })]]);
    expect(withCanvasMedia(undefined, blob, new Set([A]))).toEqual([B]);
    expect(withCanvasMedia(undefined, blob, new Set([A, B]))).toBeUndefined();
  });
});
