import { describe, it, expect, beforeEach, afterEach, jest } from '@jest/globals';
import fs from 'fs/promises';
import os from 'os';
import path from 'path';
import { SoundCaptureService } from '../SoundCaptureService';

/**
 * Extraction de bande-son d'une VIDÉO (réel) vers la bibliothèque de sons.
 *
 * L'extracteur ffmpeg est INJECTÉ : ces tests vérifient le pipeline autour de
 * lui (opt-in, dédoublonnage, création du `Sound`, résilience), pas ffmpeg.
 */

function buildPrisma(overrides: Record<string, unknown> = {}) {
  return {
    postMedia: { findMany: jest.fn<() => Promise<unknown[]>>().mockResolvedValue([]) },
    user: { findUnique: jest.fn<() => Promise<unknown>>().mockResolvedValue({ username: 'tester' }) },
    sound: {
      findFirst: jest.fn<() => Promise<unknown>>().mockResolvedValue(null),
      findMany: jest.fn<() => Promise<unknown[]>>().mockResolvedValue([]),
      create: jest.fn<() => Promise<unknown>>().mockResolvedValue({ id: 'sound-1' }),
      update: jest.fn<() => Promise<unknown>>().mockResolvedValue({}),
    },
    soundUsage: {
      upsert: jest.fn<() => Promise<unknown>>().mockResolvedValue({}),
      deleteMany: jest.fn<() => Promise<unknown>>().mockResolvedValue({ count: 0 }),
      findMany: jest.fn<() => Promise<unknown[]>>().mockResolvedValue([]),
      count: jest.fn<() => Promise<number>>().mockResolvedValue(0),
    },
    ...overrides,
  } as unknown as import('@meeshy/shared/prisma/client').PrismaClient;
}

describe('SoundCaptureService — extraction vidéo', () => {
  let soundsDir: string;
  let uploadsRoot: string;
  const ORIGINAL_FLAG = process.env.SOUND_LIBRARY_ENABLED;

  beforeEach(async () => {
    process.env.SOUND_LIBRARY_ENABLED = 'true';
    soundsDir = await fs.mkdtemp(path.join(os.tmpdir(), 'sounds-'));
    uploadsRoot = await fs.mkdtemp(path.join(os.tmpdir(), 'uploads-'));
  });

  afterEach(async () => {
    if (ORIGINAL_FLAG === undefined) delete process.env.SOUND_LIBRARY_ENABLED;
    else process.env.SOUND_LIBRARY_ENABLED = ORIGINAL_FLAG;
    await fs.rm(soundsDir, { recursive: true, force: true });
    await fs.rm(uploadsRoot, { recursive: true, force: true });
  });

  async function seedVideo(id: string) {
    const rel = path.join('2026', '08', 'user-1', `${id}.mp4`);
    await fs.mkdir(path.dirname(path.join(uploadsRoot, rel)), { recursive: true });
    await fs.writeFile(path.join(uploadsRoot, rel), `video-bytes-${id}`);
    return {
      id, fileUrl: `/u/${id}.mp4`, filePath: rel, mimeType: 'video/mp4',
      duration: 9000, language: 'fr',
    };
  }

  /** Extracteur factice : écrit des octets déterministes là où ffmpeg écrirait. */
  const fakeExtractor = (payload: string) =>
    jest.fn<(input: string, output: string) => Promise<void>>()
      .mockImplementation(async (_input, output) => { await fs.writeFile(output, payload); });

  function makeService(prisma: ReturnType<typeof buildPrisma>,
                       extractor: (input: string, output: string) => Promise<void>) {
    return new SoundCaptureService(prisma, soundsDir, uploadsRoot, extractor);
  }

  it('test_videoTrackWithOptIn_createsSoundCreditedToAuthorWithProvenance', async () => {
    const media = await seedVideo('v1');
    const prisma = buildPrisma({
      postMedia: { findMany: jest.fn<() => Promise<unknown[]>>().mockResolvedValue([media]) },
    });
    const extractor = fakeExtractor('aac-bytes');

    await makeService(prisma, extractor).captureSounds({
      postId: 'p1', authorId: 'u1', feedsLibrary: true,
      tracks: [{ trackId: 'media:v1', postMediaId: 'v1', extractFromVideo: true }],
    });

    expect(extractor).toHaveBeenCalledTimes(1);
    expect(prisma.sound.create).toHaveBeenCalledWith(expect.objectContaining({
      data: expect.objectContaining({
        uploaderId: 'u1',
        sourcePostId: 'p1',
        canonicalPostMediaId: 'v1',
        mimeType: 'audio/mp4',
        durationMs: 9000,
        sourceLanguage: 'fr',
        title: '',
        isAutoGenerated: true,
      }),
    }));
    expect(prisma.soundUsage.upsert).toHaveBeenCalled();
    // Le fichier de bibliothèque est bien la COPIE du flux extrait.
    const files = await fs.readdir(soundsDir);
    expect(files).toHaveLength(1);
    expect(files[0]!.endsWith('.m4a')).toBe(true);
    expect(await fs.readFile(path.join(soundsDir, files[0]!), 'utf8')).toBe('aac-bytes');
  });

  it('test_videoTrackWithoutExtractFlag_isIgnored', async () => {
    // La piste vidéo sans `extractFromVideo` (ex. blob client hostile qui
    // désigne un mp4 dans storyEffects) ne déclenche NI extraction NI capture.
    const media = await seedVideo('v1');
    const prisma = buildPrisma({
      postMedia: { findMany: jest.fn<() => Promise<unknown[]>>().mockResolvedValue([media]) },
    });
    const extractor = fakeExtractor('aac-bytes');

    await makeService(prisma, extractor).captureSounds({
      postId: 'p1', authorId: 'u1', feedsLibrary: true,
      tracks: [{ trackId: 't1', postMediaId: 'v1' }],
    });

    expect(extractor).not.toHaveBeenCalled();
    expect(prisma.sound.create).not.toHaveBeenCalled();
  });

  it('test_extractFlagOnAudioMedia_takesThePlainAudioPath', async () => {
    // Défense en profondeur : même si le flag fuyait sur un média audio, le
    // chemin audio classique prime — jamais de démuxage d'un fichier audio.
    const rel = path.join('a', 'm1.m4a');
    await fs.mkdir(path.dirname(path.join(uploadsRoot, rel)), { recursive: true });
    await fs.writeFile(path.join(uploadsRoot, rel), 'audio-bytes');
    const media = { id: 'm1', fileUrl: '/u/m1.m4a', filePath: rel, mimeType: 'audio/x-m4a', duration: 4000 };
    const prisma = buildPrisma({
      postMedia: { findMany: jest.fn<() => Promise<unknown[]>>().mockResolvedValue([media]) },
    });
    const extractor = fakeExtractor('aac-bytes');

    await makeService(prisma, extractor).captureSounds({
      postId: 'p1', authorId: 'u1', feedsLibrary: true,
      tracks: [{ trackId: 'media:m1', postMediaId: 'm1', extractFromVideo: true }],
    });

    expect(extractor).not.toHaveBeenCalled();
    expect(prisma.sound.create).toHaveBeenCalled();
  });

  it('test_extractorFailure_neverRejects_createsNothing', async () => {
    const media = await seedVideo('v1');
    const prisma = buildPrisma({
      postMedia: { findMany: jest.fn<() => Promise<unknown[]>>().mockResolvedValue([media]) },
    });
    const extractor = jest.fn<(input: string, output: string) => Promise<void>>()
      .mockRejectedValue(new Error('no audio stream'));

    await expect(makeService(prisma, extractor).captureSounds({
      postId: 'p1', authorId: 'u1', feedsLibrary: true,
      tracks: [{ trackId: 'media:v1', postMediaId: 'v1', extractFromVideo: true }],
    })).resolves.toBeUndefined();

    expect(prisma.sound.create).not.toHaveBeenCalled();
    expect(prisma.soundUsage.upsert).not.toHaveBeenCalled();
  });

  it('test_emptyExtraction_createsNothing', async () => {
    const media = await seedVideo('v1');
    const prisma = buildPrisma({
      postMedia: { findMany: jest.fn<() => Promise<unknown[]>>().mockResolvedValue([media]) },
    });
    const extractor = fakeExtractor('');

    await makeService(prisma, extractor).captureSounds({
      postId: 'p1', authorId: 'u1', feedsLibrary: true,
      tracks: [{ trackId: 'media:v1', postMediaId: 'v1', extractFromVideo: true }],
    });

    expect(prisma.sound.create).not.toHaveBeenCalled();
  });

  it('test_sameExtractedStream_dedupesOnExistingSound', async () => {
    // Le hash porte sur le FLUX EXTRAIT : une republication de la même vidéo
    // retombe sur le Sound existant et n'écrit qu'un usage.
    const media = await seedVideo('v1');
    const prisma = buildPrisma({
      postMedia: { findMany: jest.fn<() => Promise<unknown[]>>().mockResolvedValue([media]) },
      sound: {
        findFirst: jest.fn<() => Promise<unknown>>().mockResolvedValue({ id: 'sound-existing' }),
        findMany: jest.fn<() => Promise<unknown[]>>().mockResolvedValue([]),
        create: jest.fn<() => Promise<unknown>>().mockResolvedValue({ id: 'unused' }),
        update: jest.fn<() => Promise<unknown>>().mockResolvedValue({}),
      },
    });
    const extractor = fakeExtractor('aac-bytes');

    await makeService(prisma, extractor).captureSounds({
      postId: 'p1', authorId: 'u1', feedsLibrary: true,
      tracks: [{ trackId: 'media:v1', postMediaId: 'v1', extractFromVideo: true }],
    });

    expect(prisma.sound.create).not.toHaveBeenCalled();
    expect(prisma.soundUsage.upsert).toHaveBeenCalledWith(expect.objectContaining({
      create: expect.objectContaining({ soundId: 'sound-existing' }),
    }));
  });
});
