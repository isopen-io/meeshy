import { CanvasV3Schema, RESERVED_KINDS } from '@meeshy/shared/types/canvas-v3';

describe('CanvasV3Schema', () => {
  const minimal = {
    v: 3,
    scenes: [{
      id: 's1',
      objects: [{
        id: 'o1', kind: 'text',
        anchor: { t: 'free', x: 0.5, y: 0.4 },
        plane: 'fg', z: 0,
        transform: { scale: 1, rotation: 0, opacity: 1 },
        payload: { text: 'Bonjour', textStyle: 'bold' },
      }],
    }],
  };

  it('parses a minimal v3 document', () => {
    expect(CanvasV3Schema.parse(minimal).v).toBe(3);
  });

  it('rejects a v1-shaped blob (no v:3)', () => {
    expect(CanvasV3Schema.safeParse({ textObjects: [] }).success).toBe(false);
  });

  it('timing is optional — nil means "suit la slide" (O4)', () => {
    expect(CanvasV3Schema.parse(minimal).scenes[0].objects[0].timing).toBeUndefined();
  });

  it('band anchor parses', () => {
    const doc = structuredClone(minimal);
    (doc.scenes[0].objects[0] as { anchor: unknown }).anchor = { t: 'band', edge: 'top' };
    expect(CanvasV3Schema.parse(doc).scenes[0].objects[0].anchor).toEqual({ t: 'band', edge: 'top' });
  });

  it.each(RESERVED_KINDS)('refuses the RESERVED kind %s with a dedicated message', (kind) => {
    const doc = structuredClone(minimal);
    (doc.scenes[0].objects[0] as { kind: string }).kind = kind;
    const res = CanvasV3Schema.safeParse(doc);
    expect(res.success).toBe(false);
    if (!res.success) expect(JSON.stringify(res.error.issues)).toContain('KIND_RESERVED');
  });

  it('background sound carries its PROVENANCE (original vs library)', () => {
    const doc = structuredClone(minimal) as Record<string, unknown>;
    doc.sound = { source: { t: 'library', soundId: 'snd1' }, volume: 0.6, bounds: { start: 2, end: 17 } };
    expect(CanvasV3Schema.parse(doc).sound?.source).toEqual({ t: 'library', soundId: 'snd1' });
  });

  const withTiming = (timing: Record<string, unknown>) => {
    const doc = structuredClone(minimal);
    (doc.scenes[0].objects[0] as { timing?: unknown }).timing = timing;
    return doc;
  };

  it('refuses an object timing that ends BEFORE it starts (end < start)', () => {
    const res = CanvasV3Schema.safeParse(withTiming({ start: 4, end: 1 }));
    expect(res.success).toBe(false);
  });

  it('accepts a zero-duration object timing (end === start)', () => {
    expect(CanvasV3Schema.parse(withTiming({ start: 2, end: 2 })).scenes[0].objects[0].timing)
      .toEqual({ start: 2, end: 2 });
  });

  it('accepts a partial timing that omits one bound (only start, or only end)', () => {
    expect(CanvasV3Schema.parse(withTiming({ start: 1 })).scenes[0].objects[0].timing).toEqual({ start: 1 });
    expect(CanvasV3Schema.parse(withTiming({ end: 3 })).scenes[0].objects[0].timing).toEqual({ end: 3 });
  });

  const withBounds = (bounds: Record<string, unknown>) => {
    const doc = structuredClone(minimal) as Record<string, unknown>;
    doc.sound = { source: { t: 'original' }, volume: 1, bounds };
    return doc;
  };

  it('refuses a background-sound bounds that ends BEFORE it starts (end < start)', () => {
    const res = CanvasV3Schema.safeParse(withBounds({ start: 17, end: 2 }));
    expect(res.success).toBe(false);
  });

  it('accepts zero-duration background-sound bounds (end === start)', () => {
    expect(CanvasV3Schema.parse(withBounds({ start: 5, end: 5 })).sound?.bounds).toEqual({ start: 5, end: 5 });
  });
});

describe('CanvasV3Schema — contrat étendu (rattrapage B8a)', () => {
  const scene = {
    id: 's1',
    objects: [{
      id: 'o1', kind: 'text',
      anchor: { t: 'free', x: 0.5, y: 0.4 },
      plane: 'fg', z: 0,
      transform: { scale: 1, rotation: 0, opacity: 1 },
      payload: { text: 'Bonjour' },
    }],
  };

  it('scenes is OPTIONAL — un document sans objet ne porte pas de cadre vide (O3)', () => {
    expect(CanvasV3Schema.safeParse({ v: 3 }).success).toBe(true);
  });

  it('but an EMPTY scenes array stays refused (min 1 quand la clé est là)', () => {
    expect(CanvasV3Schema.safeParse({ v: 3, scenes: [] }).success).toBe(false);
  });

  it('a scene carries the slide thumbHash', () => {
    const doc = { v: 3, scenes: [{ ...scene, thumbHash: '1QcSHQRnh493V4dIh4eXh0h4kJUI' }] };
    expect(CanvasV3Schema.parse(doc).scenes?.[0].thumbHash).toBe('1QcSHQRnh493V4dIh4eXh0h4kJUI');
  });

  it('the background sound carries its TTS variants by language', () => {
    const doc = {
      v: 3,
      scenes: [scene],
      sound: {
        source: { t: 'library', soundId: 'snd1' },
        volume: 0.6,
        variants: [{ postMediaId: '64b0000000000000000000e1', language: 'fr', isAutoGenerated: true }],
      },
    };
    expect(CanvasV3Schema.parse(doc).sound?.variants).toEqual([
      { postMediaId: '64b0000000000000000000e1', language: 'fr', isAutoGenerated: true },
    ]);
  });
});
