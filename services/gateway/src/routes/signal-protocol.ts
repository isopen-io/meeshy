/**
 * Signal Protocol API Routes
 *
 * Handles pre-key bundle generation, exchange, and session establishment
 * for end-to-end encrypted messaging.
 *
 * SECURITY:
 * - Rate limited to prevent key scraping and pre-key exhaustion
 * - Authorization checks to prevent unauthorized key access
 */

import { FastifyInstance } from 'fastify';
import { z } from 'zod';
import rateLimit from '@fastify/rate-limit';
import { getEncryptionService } from '../services/EncryptionService';
import { createUnifiedAuthMiddleware, UnifiedAuthRequest } from '../middleware/auth';
import { createSignalProtocolRateLimitConfig } from '../middleware/rate-limiter';
import { enhancedLogger } from '../utils/logger-enhanced';
import { sendSuccess, sendError, sendInternalError, sendNotFound, sendForbidden, sendBadRequest } from '../utils/response.js';
import {
  errorResponseSchema,
  validationErrorResponseSchema,
  signalPreKeyBundleSchema,
  generatePreKeyBundleRequestSchema,
  generatePreKeyBundleResponseSchema,
  getPreKeyBundleResponseSchema,
  establishSessionRequestSchema,
  establishSessionResponseSchema,
} from '@meeshy/shared/types/api-schemas';

const logger = enhancedLogger.child({ module: 'SignalProtocolRoutes' });

// Zod validation schemas
const UserIdParamsSchema = z.object({
  userId: z.string().min(1, 'User ID is required').max(255),
});

const EstablishSessionBodySchema = z.object({
  recipientUserId: z.string().min(1, 'Recipient user ID is required').max(255),
  conversationId: z.string().min(1, 'Conversation ID is required').max(255),
});

export default async function signalProtocolRoutes(fastify: FastifyInstance) {
  const prisma = fastify.prisma;
  const encryptionService = await getEncryptionService(prisma);
  const authMiddleware = createUnifiedAuthMiddleware(prisma, {
    requireAuth: true,
    allowAnonymous: false,
  });

  // Register rate limiters for Signal Protocol endpoints
  // SECURITY: Prevent key scraping, pre-key exhaustion, and session flooding
  await fastify.register(rateLimit, createSignalProtocolRateLimitConfig('keys_post') as any);

  /**
   * POST /api/signal/keys
   * Generate and store pre-key bundle for current user
   *
   * Rate limit: 5 requests/minute (key generation is rare)
   */
  fastify.post(
    '/signal/keys',
    {
      preValidation: [authMiddleware],
      config: {
        rateLimit: createSignalProtocolRateLimitConfig('keys_post')
      },
      schema: {
        description: 'Store Signal Protocol pre-key bundle generated by the authenticated user client. Keys are stored server-side and can be retrieved by authorized users.',
        tags: ['encryption', 'signal'],
        summary: 'Upload pre-key bundle',
        body: generatePreKeyBundleRequestSchema,
        response: {
          200: generatePreKeyBundleResponseSchema,
          400: errorResponseSchema,
          401: errorResponseSchema,
          500: errorResponseSchema,
        }
      }
    },
    async (request, reply) => {
      try {
        const authRequest = request as unknown as UnifiedAuthRequest;
        const userId = authRequest.authContext.userId;

        // Extract client-generated keys
        const bundle = request.body as any; // Type matches generatePreKeyBundleRequestSchema

        // Store in database
        await prisma.signalPreKeyBundle.upsert({
          where: { userId },
          create: {
            userId,
            identityKey: bundle.identityKey,
            registrationId: bundle.registrationId,
            deviceId: bundle.deviceId,
            preKeyId: bundle.preKeyId,
            preKeyPublic: bundle.preKeyPublic || null,
            signedPreKeyId: bundle.signedPreKeyId,
            signedPreKeyPublic: bundle.signedPreKeyPublic,
            signedPreKeySignature: bundle.signedPreKeySignature,
            kyberPreKeyId: bundle.kyberPreKeyId || null,
            kyberPreKeyPublic: bundle.kyberPreKeyPublic || null,
            kyberPreKeySignature: bundle.kyberPreKeySignature || null,
            createdAt: new Date(),
            lastRotatedAt: new Date(),
          },
          update: {
            identityKey: bundle.identityKey,
            registrationId: bundle.registrationId,
            deviceId: bundle.deviceId,
            preKeyId: bundle.preKeyId,
            preKeyPublic: bundle.preKeyPublic || null,
            signedPreKeyId: bundle.signedPreKeyId,
            signedPreKeyPublic: bundle.signedPreKeyPublic,
            signedPreKeySignature: bundle.signedPreKeySignature,
            kyberPreKeyId: bundle.kyberPreKeyId || null,
            kyberPreKeyPublic: bundle.kyberPreKeyPublic || null,
            kyberPreKeySignature: bundle.kyberPreKeySignature || null,
            lastRotatedAt: new Date(),
          },
        });

        logger.info('Saved pre-key bundle uploaded by client', { userId });

        return sendSuccess(reply, {
            registrationId: bundle.registrationId,
            deviceId: bundle.deviceId,
            preKeyId: bundle.preKeyId,
            signedPreKeyId: bundle.signedPreKeyId,
            message: 'Pre-key bundle uploaded successfully',
          });
      } catch (error) {
        logger.error('Error saving pre-key bundle', { err: error });
        return sendInternalError(reply, 'Failed to save pre-key bundle');
      }
    }
  );

  /**
   * GET /api/signal/keys/:userId
   * Get pre-key bundle for another user
   * Used to establish E2EE session
   *
   * Rate limit: 30 requests/minute (key lookups are more common)
   * Authorization: User must share a conversation with the target user
   */
  fastify.get<{
    Params: z.infer<typeof UserIdParamsSchema>;
  }>(
    '/signal/keys/:userId',
    {
      preValidation: [authMiddleware],
      config: {
        rateLimit: createSignalProtocolRateLimitConfig('keys_get')
      },
      schema: {
        description: 'Retrieve pre-key bundle for another user to establish an E2EE session. Requires authorization: requesting user must share a conversation or friendship with the target user. This prevents unauthorized key scraping attacks.',
        tags: ['encryption', 'signal'],
        summary: 'Get user pre-key bundle',
        params: {
          type: 'object',
          required: ['userId'],
          properties: {
            userId: {
              type: 'string',
              minLength: 1,
              maxLength: 255,
              description: 'Target user ID to fetch pre-key bundle for'
            }
          }
        },
        response: {
          200: getPreKeyBundleResponseSchema,
          // Les autres 400 de ce fichier utilisent deja le schema partage.
          // Celui-ci, ecrit a la main, supprimait `message` et `code`, et
          // declarait un tableau `details` que l'enveloppe ne pose pas comme
          // cle (elle l'ETALE a la racine) — `violations` est le sien.
          400: { description: 'Validation error', ...validationErrorResponseSchema },
          401: errorResponseSchema,
          403: {
            ...errorResponseSchema,
            properties: {
              ...errorResponseSchema.properties,
              error: { type: 'string', example: 'You are not authorized to access this user\'s encryption keys' },
            }
          },
          404: {
            ...errorResponseSchema,
            properties: {
              ...errorResponseSchema.properties,
              error: { type: 'string', example: 'User has not generated encryption keys' },
            }
          },
          500: errorResponseSchema,
        }
      }
    },
    async (request, reply) => {
      try {
        const authRequest = request as unknown as UnifiedAuthRequest;
        const requestingUserId = authRequest.authContext.userId;

        // Validate params
        const paramsResult = UserIdParamsSchema.safeParse(request.params);
        if (!paramsResult.success) {
          return sendBadRequest(reply, 'Invalid request parameters');
        }
        const { userId: targetUserId } = paramsResult.data;

        // SECURITY: Authorization check - user must share a conversation with target
        // This prevents unauthorized key scraping
        // Find conversations where the requesting user is a member
        const userConversations = await prisma.participant.findMany({
          where: { userId: requestingUserId, isActive: true },
          select: { conversationId: true }
        });
        const conversationIds = userConversations.map(c => c.conversationId);

        // Check if target user is a member of any of those conversations
        const sharedConversation = conversationIds.length > 0
          ? await prisma.participant.findFirst({
              where: {
                userId: targetUserId,
                conversationId: { in: conversationIds },
                isActive: true
              }
            })
          : null;

        // Also allow if they are friends
        const areFriends = await prisma.friendRequest.findFirst({
          where: {
            OR: [
              { senderId: requestingUserId, receiverId: targetUserId, status: 'accepted' },
              { senderId: targetUserId, receiverId: requestingUserId, status: 'accepted' }
            ]
          }
        });

        if (!sharedConversation && !areFriends) {
          logger.warn('SECURITY: Unauthorized key bundle request', {
            requestingUserId,
            targetUserId,
            reason: 'No shared conversation or friendship'
          });
          return sendForbidden(reply, 'You are not authorized to access this user\'s encryption keys');
        }

        // Fetch from database
        const bundle = await prisma.signalPreKeyBundle.findUnique({
          where: { userId: targetUserId },
          select: {
            identityKey: true,
            registrationId: true,
            deviceId: true,
            preKeyId: true,
            preKeyPublic: true,
            signedPreKeyId: true,
            signedPreKeyPublic: true,
            signedPreKeySignature: true,
            kyberPreKeyId: true,
            kyberPreKeyPublic: true,
            kyberPreKeySignature: true,
          },
        });

        if (!bundle) {
          return sendNotFound(reply, 'User has not generated encryption keys');
        }

        // The bundle is returned exactly as stored: base64 strings.
        //
        // It used to be decoded into `Uint8Array` here, which silently
        // destroyed every key on the wire. Fastify serializes a 200 through the
        // declared response schema, and `signalPreKeyBundleSchema` types these
        // fields `string` — fast-json-stringify coerces a non-string with
        // `String(value)`, and `String(Uint8Array)` is the decimal listing of
        // its bytes. A client asking for a bundle received
        // `"97,110,45,105,…"` where it expected `"YW4tabc…="`, so
        // `Data(base64Encoded:)` returned nil on iOS
        // (`E2ESessionManager.getOrCreateSession` → `invalidBase64Payload`),
        // every peer landed in the 600 s failure cooldown, and no E2EE session
        // could ever be derived.
        //
        // base64 is the format on all three sides — the column, the response
        // schema, and `E2EAPI.BackendPreKeyBundle` — so the decoding step had
        // no consumer to serve. `select` above already restricts the row to the
        // schema's own fields.
        logger.debug('Fetched pre-key bundle', { userId: targetUserId });

        return sendSuccess(reply, bundle);
      } catch (error) {
        logger.error('Error fetching pre-key bundle', { err: error });
        return sendInternalError(reply, 'Failed to fetch pre-key bundle');
      }
    }
  );

  /**
   * POST /api/signal/session/establish
   * Establish E2EE session with another user
   *
   * Rate limit: 20 requests/minute (session creation)
   * Authorization: User must be a participant in the conversation
   */
  fastify.post<{
    Body: z.infer<typeof EstablishSessionBodySchema>;
  }>(
    '/signal/session/establish',
    {
      preValidation: [authMiddleware],
      config: {
        rateLimit: createSignalProtocolRateLimitConfig('session_establish')
      },
      schema: {
        description: 'Establish an end-to-end encrypted session with another user in a conversation. Validates that both users are participants in the specified conversation. Fetches recipient pre-key bundle and marks one-time pre-keys as consumed. Requires Signal Protocol library for full E2EE functionality.',
        tags: ['encryption', 'signal'],
        summary: 'Establish E2EE session',
        body: establishSessionRequestSchema,
        response: {
          200: establishSessionResponseSchema,
          400: {
            description: 'Validation error or recipient not in conversation',
            ...validationErrorResponseSchema
          },
          401: errorResponseSchema,
          403: {
            ...errorResponseSchema,
            properties: {
              ...errorResponseSchema.properties,
              error: { type: 'string', example: 'You are not a participant in this conversation' },
            }
          },
          404: {
            ...errorResponseSchema,
            properties: {
              ...errorResponseSchema.properties,
              error: { type: 'string', example: 'Recipient has not generated encryption keys' },
            }
          },
          500: errorResponseSchema,
        }
      }
    },
    async (request, reply) => {
      try {
        // Validate request body
        const authRequest = request as unknown as UnifiedAuthRequest;
        const userId = authRequest.authContext.userId;

        const bodyResult = EstablishSessionBodySchema.safeParse(request.body);
        if (!bodyResult.success) {
          return sendBadRequest(reply, 'Invalid request body');
        }
        const { recipientUserId, conversationId } = bodyResult.data;

        // SECURITY: Verify user is an ACTIVE participant in the conversation.
        //
        // `isActive: true` n'est pas décoratif ici. Un départ ne supprime pas la
        // ligne `Participant`, il la passe à `isActive: false` — et cette route
        // consomme la pré-clé à usage unique du destinataire un peu plus bas.
        // Sans ce filtre, un ancien membre qui a gardé l'identifiant de
        // conversation en cache local détruisait à volonté la pré-clé de
        // n'importe quel membre resté : l'épuisement de pré-clés que l'en-tête
        // de ce fichier dit prévenir, par la porte qui ne vérifiait pas ce que
        // `GET /signal/keys/:userId` vérifie cent lignes plus haut sur ses DEUX
        // côtés.
        const isParticipant = await prisma.participant.findFirst({
          where: {
            userId,
            conversationId,
            isActive: true
          }
        });

        if (!isParticipant) {
          logger.warn('SECURITY: Unauthorized session establishment attempt', {
            userId,
            recipientUserId,
            conversationId,
            reason: 'User is not a participant in the conversation'
          });
          return sendForbidden(reply, 'You are not a participant in this conversation');
        }

        // SECURITY: Verify recipient is also an ACTIVE participant — chiffrer
        // vers quelqu'un qui a quitté la conversation revient à ouvrir une
        // session avec un destinataire qui n'y lira plus rien, tout en brûlant
        // sa pré-clé.
        const recipientIsParticipant = await prisma.participant.findFirst({
          where: {
            userId: recipientUserId,
            conversationId,
            isActive: true
          }
        });

        if (!recipientIsParticipant) {
          return sendBadRequest(reply, 'Recipient is not a participant in this conversation');
        }

        // Fetch recipient's pre-key bundle
        const bundle = await prisma.signalPreKeyBundle.findUnique({
          where: { userId: recipientUserId },
        });

        if (!bundle) {
          return sendNotFound(reply, 'Recipient has not generated encryption keys');
        }

        // Use Signal Protocol service to establish session
        const signalService = encryptionService.getSignalService();
        if (!signalService) {
          logger.warn('Signal Protocol not available, refusing to fake E2EE session', {
            userId,
            recipientUserId,
            conversationId,
          });

          return sendError(reply, 503, 'E2EE_UNAVAILABLE', { message: 'End-to-end encryption is not available on this server' });
        }

        // This route AUTHORIZES a session; it does not establish one, and it no
        // longer consumes the recipient's one-time pre-key.
        //
        // It used to null `preKeyId`/`preKeyPublic` here. Nothing received what
        // it destroyed: the response carries a message and no key material, and
        // the bundle this handler built from the row was never read by anything
        // (removed with this change). Consumption belongs to whichever route
        // DISTRIBUTES the pre-key — `GET /signal/keys/:userId` — never to a
        // route that hands the caller nothing.
        //
        // Left as it was, any active participant could strip any other member's
        // one-time pre-key at the route's rate limit, and nothing replenishes
        // it: clients upload a bundle once, on the authentication edge. That is
        // the pre-key exhaustion this file's header says it prevents.
        //
        // The one-time pre-key is consequently still handed out more than once
        // — a real weakness, but a pre-existing one that needs a pool of
        // pre-keys (the schema holds a single slot) and a client-side
        // replenishment path to fix. Recorded as open rather than half-fixed
        // here: claiming the only slot on first fetch would leave every later
        // peer without one and nothing to refill it.
        logger.info('Authorized E2EE session establishment', {
          userId,
          recipientUserId,
          conversationId,
        });

        return sendSuccess(reply, { message: 'E2EE session established successfully' });
      } catch (error) {
        logger.error('Error establishing session', { err: error });
        return sendInternalError(reply, 'Failed to establish E2EE session');
      }
    }
  );
}
